"""Rewrite the <!-- assets:begin --> … <!-- assets:end --> block in every page from tools/manifest.json.

Usage:  python3 tools/sync_assets.py          # write
        python3 tools/sync_assets.py --check  # verify only (non-zero exit on drift)

Fails if a manifest entry does not exist, or if any .js/.css file under js/ or css/ is
not referenced by any page (so a new module can't be silently forgotten).
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
M = json.loads((ROOT / "tools" / "manifest.json").read_text())
G = M["groups"]


def expand(items, seen=()):
    out = []
    for it in items:
        if it.startswith("@"):
            if it in seen:
                sys.exit(f"cycle in group {it}")
            out += expand(G[it], seen + (it,))
        elif it not in out:
            out.append(it)
    return out


def block(page):
    spec = M["pages"][page]
    css = expand(spec["styles"])
    js = expand(spec["scripts"])
    lines = [
        "  <!-- assets:begin (generated by tools/sync_assets.py "
        "from tools/manifest.json — do not edit by hand) -->"
    ]
    lines += [f'  <link rel="stylesheet" href="{p}">' for p in css]
    lines += [f'  <script src="{p}" defer></script>' for p in js]
    lines.append("  <!-- assets:end -->")
    return "\n".join(lines), css + js


def asset_pattern():
    return r"  <!-- assets:begin.*?<!-- assets:end -->"


def strip_head_tags(fragment):
    pattern = (
        r'\n\s*<link rel="stylesheet"[^>]*>'
        r'|\n\s*<script src="[^"]*"( defer)?></script>'
    )
    return re.sub(pattern, "", fragment)


def main():
    check = "--check" in sys.argv
    used, errors, drift = set(), [], []
    for page in M["pages"]:
        path = ROOT / page
        html = path.read_text()
        new, files = block(page)
        used.update(files)
        errors += [f"{page}: missing {f}" for f in files if not (ROOT / f).exists()]
        if "<!-- assets:begin" in html:
            out = re.sub(asset_pattern(), lambda _match, text=new: text, html, flags=re.S)
        else:  # first run: strip hand-written stylesheet/script tags from <head>
            head_end = html.index("</head>")
            head = strip_head_tags(html[:head_end])
            out = head.rstrip() + "\n" + new + "\n" + html[head_end:]
        if out != html:
            drift.append(page)
            if not check:
                path.write_text(out)
    on_disk = {
        str(p.relative_to(ROOT))
        for d in ("js", "css")
        for p in (ROOT / d).rglob("*")
        if p.suffix in (".js", ".css")
    }
    errors += [f"unreferenced: {f} (add it to tools/manifest.json)" for f in sorted(on_disk - used)]
    for e in errors:
        print("ERROR", e)
    if check and drift:
        print("OUT OF DATE:", ", ".join(drift))
    elif drift:
        print("updated:", ", ".join(drift))
    else:
        print("assets in sync")
    sys.exit(1 if errors or (check and drift) else 0)


main()
