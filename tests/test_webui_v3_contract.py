# --- Subsystem A: v3 asset serving -------------------------------------------

EXPECTED_PAGES = (
    "index.html",
    "console.html",
    "demo.html",
    "prod-setup.html",
    "demo-setup.html",
    "visualizer.html",
)


def test_web_dir_holds_v3_entry_points():
    web = ROOT / "web"
    assert web.is_dir(), "web/ missing: v3 assets not migrated"
    for page in EXPECTED_PAGES:
        assert (web / page).is_file(), f"web/{page} missing"


def test_web_manifest_pipeline_in_sync():
    manifest = ROOT / "web" / "tools" / "manifest.json"
    syncer = ROOT / "web" / "tools" / "sync_assets.py"
    assert manifest.is_file() and syncer.is_file(), "manifest/sync_assets.py missing"
    import json
    import subprocess

    out = subprocess.run(
        ["python3", str(syncer), "--check"],
        capture_output=True,
        text=True,
        cwd=str(ROOT / "web"),
    )
    assert out.returncode == 0, f"sync_assets --check failed:\n{out.stdout}\n{out.stderr}"
    pages = json.loads(manifest.read_text())["pages"]
    for page in EXPECTED_PAGES:
        assert page in pages, f"manifest missing page {page}"


def test_server_serves_v3_pages_from_web():
    with TestClient(_client(), base_url="http://localhost") as client:
        for page in EXPECTED_PAGES:
            resp = client.get(f"/web/{page}")
            assert resp.status_code == 200, f"/web/{page} -> {resp.status_code}"
            assert "assets:begin" in resp.text, f"/web/{page} missing synced asset block"
        # v2 dashboard keeps `/`; v3 index is identical path under /web/.
        assert client.get("/").status_code == 200


def test_asset_block_never_hand_edited():
    web = ROOT / "web"
    for page in EXPECTED_PAGES:
        text = (web / page).read_text()
        assert "generated by tools/sync_assets.py" in text, f"{page} not sync-generated"


