def test_log_frame_accepts_ts_alias():
    """WS log frames must carry a server timestamp the v3 eventTime() reads."""
    import asyncio

    from library.services.chatter import socket_emit

    seen: list[dict] = []

    class FakeSocket:
        async def send_json(self, payload):
            seen.append(payload)

    async def go():
        emit = socket_emit(FakeSocket())
        await emit("red", "Boundary check exited 0.")

    asyncio.run(go())
    assert seen and seen[0]["team"] == "red"
    assert seen[0].get("type") == "log"
    assert "ts" in seen[0], f"log frame missing ts alias: {seen[0]}"


# --- Subsystem C: snapshot hydration + broadcast batching ---------------------


def test_ws_emits_connect_snapshot_before_workflow():
    """On accept, server sends a state snapshot (v3 onGraph/onLine hydration)."""
    from library.core.config import PurpleBoxConfig
    from main import create_app

    with TestClient(create_app(PurpleBoxConfig()), base_url="http://localhost") as client:
        with client.websocket_connect(
            "ws://localhost/ws/combat/node_query_sink",
            headers={"origin": "http://localhost"},
        ) as sock:
            first = sock.receive_json()
            assert first.get("type") == "snapshot", f"first frame not snapshot: {first}"
            for key in ("nodes", "hud", "chips"):
                assert key in first, f"snapshot missing {key}"
            assert set(first["hud"]) >= {"nodes", "msgs", "findings", "patches", "verified"}


def test_telemetry_batcher_coalesces_rapid_events():
    """100-250ms batching: rapid telemetry emits collapse to bounded frames."""
    import asyncio

    from library.services import telemetry_hub as hub

    assert hasattr(hub, "TelemetryBatcher"), "TelemetryBatcher missing"
    frames: list[dict] = []

    async def go():
        batcher = hub.TelemetryBatcher(lambda f: frames.append(f), window_ms=100)
        for i in range(20):
            await batcher.push({"team": "telemetry", "msg": f"tick {i}"})
            await asyncio.sleep(0.005)
        await asyncio.sleep(0.15)
        await batcher.flush()

    asyncio.run(go())
    assert 1 <= len(frames) <= 4, f"expected coalesced frames, got {len(frames)}"


